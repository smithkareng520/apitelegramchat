# 以下为派生数据与辅助函数，一般无需修改
# ─────────────────────────────────────────────────────────────────

ROLE_NAMES: list[str] = [r.name for r in ROLES]
_ROLE_BY_NAME: dict[str, Role] = {r.name: r for r in ROLES}

if len(_ROLE_BY_NAME) != len(ROLES):
    raise RuntimeError("roles.py：存在重复的角色名，请检查 ROLES 列表")


def build_role_prompt(name: str | None, username: str = "用户") -> str:
    """返回角色提示词（已替换 {username}）；name 为空或未知时返回空串。

    username 应已是 Telegram HTML 安全的片段（由调用方转义）。
    用 str.replace 而不是 str.format，避免提示词里出现花括号时报错。
    """
    role = _ROLE_BY_NAME.get(name or "")
    if role is None:
        return ""
    return role.prompt.replace("{username}", username)
